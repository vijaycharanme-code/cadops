use serde::{Deserialize, Serialize};

#[derive(Debug, Serialize, Deserialize, Clone)]
pub struct StructuredSpec {
    pub part_name: String,
    pub dimensions: BracketDimensions,
    pub material: String,
    pub load_n: f64,
    pub missing_assumptions: Vec<String>,
}

#[derive(Debug, Serialize, Deserialize, Clone)]
pub struct BracketDimensions {
    pub length: f64,
    pub width: f64,
    pub height: f64,
    pub thickness: f64,
    pub hole_radius: f64,
}

#[derive(Debug, Serialize, Deserialize, Clone)]
pub struct AIResponse {
    pub structured_spec: StructuredSpec,
    pub suggested_scad: String,
    pub engineering_explanation: String,
    pub missing_assumptions: Vec<String>,
}

pub fn process_natural_language_prompt(prompt: &str) -> AIResponse {
    let lower = prompt.to_lowercase();
    let mut missing = Vec::new();

    let mut length = 60.0;
    let mut width = 30.0;
    let mut height = 50.0;
    let mut thickness = 6.0;
    let hole_radius = 4.0;
    let mut load = 100.0;

    if lower.contains("thicker") || lower.contains("stiffer") || lower.contains("deflection") {
        thickness = 8.5;
    }

    if !lower.contains("load") && !lower.contains("n") {
        missing.push("Load magnitude not explicitly specified; assumed 100 N downward.".to_string());
    } else {
        load = 100.0;
    }

    if !lower.contains("6061") && !lower.contains("aluminum") {
        missing.push("Material grade not specified; defaulted to Aluminum 6061-T6 (E=70GPa, Sy=276MPa).".to_string());
    }

    let scad = format!(
        "// Generated by CADMind Llama Assistant\nlength = {:.1};\nwidth = {:.1};\nheight = {:.1};\nthickness = {:.1};\nhole_radius = {:.1};\n\ndifference() {{\n  union() {{\n    cube([length, width, thickness]);\n    cube([thickness, width, height]);\n  }}\n  translate([length * 0.7, width / 2, -1])\n    cylinder(r=hole_radius, h=thickness + 2, $fn=32);\n  translate([-1, width / 2, height * 0.7])\n    rotate([0, 90, 0])\n      cylinder(r=hole_radius, h=thickness + 2, $fn=32);\n}}\n",
        length, width, height, thickness, hole_radius
    );

    let explanation = format!(
        "Interpreted request for parametric mounting bracket. Created an L-bracket configuration with {:.1}x{:.1}x{:.1} mm envelope, {:.1} mm wall thickness, and M8 mounting clearance holes. Configured for {:.0} N static load.",
        length, width, height, thickness, load
    );

    AIResponse {
        structured_spec: StructuredSpec {
            part_name: "Parametric L-Bracket".to_string(),
            dimensions: BracketDimensions {
                length,
                width,
                height,
                thickness,
                hole_radius,
            },
            material: "Aluminum 6061-T6".to_string(),
            load_n: load,
            missing_assumptions: missing.clone(),
        },
        suggested_scad: scad,
        engineering_explanation: explanation,
        missing_assumptions: missing,
    }
}

pub fn explain_simulation_results(max_disp_mm: f64, max_stress_mpa: f64, yield_strength: f64) -> String {
    let fos = if max_stress_mpa > 0.0 {
        yield_strength / max_stress_mpa
    } else {
        999.0
    };
    if fos < 1.5 {
        format!(
            "FEA analysis indicates high stress concentration at the inner corner bend (Peak Von Mises: {:.1} MPa, FoS: {:.2} against Sy={:.0} MPa). Maximum tip deflection is {:.4} mm. Recommendation: Increase wall thickness from 6.0 mm to 8.5 mm or add an interior triangular gusset/fillet to reduce stress by ~40%.",
            max_stress_mpa, fos, yield_strength, max_disp_mm
        )
    } else {
        format!(
            "Design operates well within elastic bounds (Peak Von Mises: {:.1} MPa, FoS: {:.2}). Tip deflection is {:.4} mm. The part is structurally sound under static 100 N loading.",
            max_stress_mpa, fos, max_disp_mm
        )
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn test_process_prompt() {
        let resp = process_natural_language_prompt("Create an aluminum mounting bracket with 100 N load");
        assert_eq!(resp.structured_spec.material, "Aluminum 6061-T6");
        assert!(resp.suggested_scad.contains("difference()"));
    }

    #[test]
    fn test_explain_results() {
        let expl = explain_simulation_results(0.25, 45.0, 276.0);
        assert!(expl.contains("FoS"));
    }
}
