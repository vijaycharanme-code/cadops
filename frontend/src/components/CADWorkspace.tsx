import React, { useState } from "react";
import { CADViewport } from "./CADViewport";

interface CADWorkspaceProps {
  scadCode: string;
  setScadCode: (code: string) => void;
  onSendToSimulation?: () => void;
}

export const CADWorkspace: React.FC<CADWorkspaceProps> = ({
  scadCode,
  setScadCode,
  onSendToSimulation,
}) => {
  const [wireframe, setWireframe] = useState(false);
  const [isRendering, setIsRendering] = useState(false);
  const [length, setLength] = useState(60);
  const [width, setWidth] = useState(30);
  const [height, setHeight] = useState(50);
  const [thickness, setThickness] = useState(6);
  const [stlBlobUrl, setStlBlobUrl] = useState<string | undefined>();

  const updateParametricScad = (l: number, w: number, h: number, t: number) => {
    const updated = `// Generated by CADMind Llama Assistant\nlength = ${l};\nwidth = ${w};\nheight = ${h};\nthickness = ${t};\nhole_radius = 4;\n\ndifference() {\n  union() {\n    cube([length, width, thickness]);\n    cube([thickness, width, height]);\n  }\n  translate([length * 0.7, width / 2, -1])\n    cylinder(r=hole_radius, h=thickness + 2, $fn=32);\n  translate([-1, width / 2, height * 0.7])\n    rotate([0, 90, 0])\n      cylinder(r=hole_radius, h=thickness + 2, $fn=32);\n}\n`;
    setScadCode(updated);
  };

  const handleRender = async () => {
    setIsRendering(true);
    try {
      const res = await fetch("http://127.0.0.1:8000/api/cad/render", {
        method: "POST",
        headers: { "Content-Type": "application/json" },
        body: JSON.stringify({ scad: scadCode }),
      });
      if (!res.ok) throw new Error("Render failed");
      const blob = await res.blob();
      const url = URL.createObjectURL(blob);
      setStlBlobUrl(url);
    } catch (e) {
      console.error(e);
    } finally {
      setIsRendering(false);
    }
  };

  const exportScad = () => {
    const blob = new Blob([scadCode], { type: "text/plain" });
    const url = URL.createObjectURL(blob);
    const a = document.createElement("a");
    a.href = url;
    a.download = "mounting_bracket.scad";
    a.click();
  };

  return (
    <div className="flex h-full w-full bg-zinc-950 text-zinc-100">
      <div className="w-1/2 flex flex-col border-r border-zinc-800">
        <div className="p-3 bg-zinc-900 border-b border-zinc-800 flex justify-between items-center">
          <span className="font-semibold text-sm text-cyan-400">OpenSCAD Editor</span>
          <div className="space-x-2">
            <button onClick={exportScad} className="px-3 py-1 bg-zinc-800 hover:bg-zinc-700 text-xs rounded border border-zinc-700">Export SCAD</button>
            <button onClick={handleRender} disabled={isRendering} className="px-3 py-1 bg-cyan-600 hover:bg-cyan-500 text-xs rounded font-medium disabled:opacity-50">{isRendering ? "Rendering..." : "Render Geometry"}</button>
          </div>
        </div>
        <textarea value={scadCode} onChange={(e) => setScadCode(e.target.value)} className="flex-1 bg-zinc-950 p-4 font-mono text-xs text-zinc-200 outline-none resize-none leading-relaxed" spellCheck={false} />
        <div className="p-4 bg-zinc-900/50 border-t border-zinc-800 space-y-3">
          <div className="text-xs font-semibold text-zinc-400 uppercase tracking-wider">Parametric Dimension Controls</div>
          <div className="grid grid-cols-2 gap-4 text-xs">
            <div>
              <label className="text-zinc-400 flex justify-between">Length: <span>{length} mm</span></label>
              <input type="range" min="30" max="120" value={length} onChange={(e) => { const v = Number(e.target.value); setLength(v); updateParametricScad(v, width, height, thickness); }} className="w-full accent-cyan-500" />
            </div>
            <div>
              <label className="text-zinc-400 flex justify-between">Thickness: <span>{thickness} mm</span></label>
              <input type="range" min="3" max="15" step="0.5" value={thickness} onChange={(e) => { const v = Number(e.target.value); setThickness(v); updateParametricScad(length, width, height, v); }} className="w-full accent-cyan-500" />
            </div>
          </div>
        </div>
      </div>
      <div className="w-1/2 flex flex-col">
        <div className="p-3 bg-zinc-900 border-b border-zinc-800 flex justify-between items-center">
          <span className="font-semibold text-sm text-zinc-300">3D Interactive Viewport</span>
          <div className="space-x-3 flex items-center">
            <label className="text-xs text-zinc-400 flex items-center gap-1 cursor-pointer">
              <input type="checkbox" checked={wireframe} onChange={(e) => setWireframe(e.target.checked)} className="accent-cyan-500" />
              Wireframe
            </label>
            {onSendToSimulation && (
              <button onClick={onSendToSimulation} className="px-3 py-1 bg-emerald-600 hover:bg-emerald-500 text-xs rounded font-medium">Send to FEA Studio</button>
            )}
          </div>
        </div>
        <div className="flex-1 relative">
          <CADViewport stlUrl={stlBlobUrl} wireframe={wireframe} />
          <div className="absolute bottom-4 left-4 bg-zinc-900/80 backdrop-blur border border-zinc-800 rounded p-2 text-xs text-zinc-400 space-y-1">
            <div>Controls: Left Click + Drag to rotate</div>
            <div>Scroll to zoom</div>
          </div>
        </div>
      </div>
    </div>
  );
};
