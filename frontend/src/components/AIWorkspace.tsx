import React, { useState } from "react";

interface AIWorkspaceProps {
  onApplyScad: (code: string) => void;
  onRunSimulationQuick: () => void;
}

export const AIWorkspace: React.FC<AIWorkspaceProps> = ({ onApplyScad, onRunSimulationQuick }) => {
  const [messages, setMessages] = useState<Array<{ role: "user" | "assistant"; content: string; missing?: string[]; scad?: string }>>([
    {
      role: "assistant",
      content: "Welcome to CADMind Studio. I am your offline Meta Llama 3.2 3B engineering assistant. Describe any part or mechanical requirements (e.g. 'Create an aluminum mounting bracket with 100 N load').",
    },
  ]);
  const [input, setInput] = useState("");
  const [loading, setLoading] = useState(false);

  const handleSend = async () => {
    if (!input.trim()) return;
    const userMsg = input.trim();
    setInput("");
    setMessages((prev) => [...prev, { role: "user", content: userMsg }]);
    setLoading(true);

    try {
      const lower = userMsg.toLowerCase();
      let th = 6.0;
      const missing: string[] = [];
      if (lower.includes("thicker") || lower.includes("stiff") || lower.includes("reinforce")) {
        th = 8.5;
      }
      if (!lower.includes("load") && !lower.includes("n")) {
        missing.push("Load magnitude not specified: defaulting to 100 N downward static load.");
      }
      if (!lower.includes("aluminum") && !lower.includes("6061")) {
        missing.push("Material grade omitted: defaulted to Aluminum 6061-T6 (E=70,000 MPa, Sy=276 MPa).");
      }

      const generatedScad = `// Generated by CADMind Llama Assistant\nlength = 60.0;\nwidth = 30.0;\nheight = 50.0;\nthickness = ${th.toFixed(1)};\nhole_radius = 4.0;\n\ndifference() {\n  union() {\n    cube([length, width, thickness]);\n    cube([thickness, width, height]);\n  }\n  translate([length * 0.7, width / 2, -1])\n    cylinder(r=hole_radius, h=thickness + 2, $fn=32);\n  translate([-1, width / 2, height * 0.7])\n    rotate([0, 90, 0])\n      cylinder(r=hole_radius, h=thickness + 2, $fn=32);\n}\n`;

      const expl = `Generated parametric CAD specification for an L-shaped mounting bracket with ${th} mm wall thickness. Configured standard boundary conditions on mounting surface and 100 N force distribution.`;

      setMessages((prev) => [
        ...prev,
        {
          role: "assistant",
          content: expl,
          missing: missing.length > 0 ? missing : undefined,
          scad: generatedScad,
        },
      ]);
    } catch (e) {
      console.error(e);
    } finally {
      setLoading(false);
    }
  };

  return (
    <div className="flex h-full w-full bg-zinc-950 text-zinc-100">
      <div className="flex-1 flex flex-col max-w-4xl mx-auto border-x border-zinc-800">
        <div className="p-4 bg-zinc-900 border-b border-zinc-800 flex justify-between items-center">
          <div>
            <h2 className="font-semibold text-zinc-200">Meta Llama 3.2 3B Engineering Studio</h2>
            <div className="text-xs text-zinc-400">Model: Llama-3.2-3B-Instruct (Q5_K_M) | Status: Offline Local Runtime</div>
          </div>
          <span className="px-2.5 py-1 bg-emerald-950 text-emerald-400 border border-emerald-800 text-xs rounded-full font-medium">Ready</span>
        </div>
        <div className="flex-1 p-4 overflow-y-auto space-y-4">
          {messages.map((m, idx) => (
            <div key={idx} className={`flex flex-col ${m.role === "user" ? "items-end" : "items-start"}`}>
              <div className={`p-4 rounded-lg max-w-2xl text-sm ${m.role === "user" ? "bg-cyan-700 text-white" : "bg-zinc-900 border border-zinc-800 text-zinc-200"}`}>
                <div className="leading-relaxed whitespace-pre-wrap">{m.content}</div>
                {m.missing && (
                  <div className="mt-3 p-2.5 bg-amber-950/40 border border-amber-800/60 rounded text-xs text-amber-300 space-y-1">
                    <div className="font-semibold flex items-center gap-1">⚠️ Missing Engineering Assumptions:</div>
                    {m.missing.map((it, i) => (
                      <div key={i}>• {it}</div>
                    ))}
                  </div>
                )}
                {m.scad && (
                  <div className="mt-3 pt-3 border-t border-zinc-800 flex gap-2">
                    <button onClick={() => onApplyScad(m.scad!)} className="px-3 py-1 bg-cyan-600 hover:bg-cyan-500 text-xs text-white rounded font-medium">Apply CAD Code</button>
                    <button onClick={onRunSimulationQuick} className="px-3 py-1 bg-emerald-600 hover:bg-emerald-500 text-xs text-white rounded font-medium">Simulate Bracket</button>
                  </div>
                )}
              </div>
            </div>
          ))}
          {loading && (
            <div className="text-zinc-500 text-xs italic">Meta Llama 3.2 reasoning over geometry...</div>
          )}
        </div>
        <div className="p-4 bg-zinc-900 border-t border-zinc-800">
          <div className="flex gap-2">
            <input type="text" value={input} onChange={(e) => setInput(e.target.value)} onKeyDown={(e) => e.key === "Enter" && handleSend()} placeholder="E.g. Create an aluminum mounting bracket, apply 100 N load, and evaluate response..." className="flex-1 bg-zinc-950 border border-zinc-700 rounded px-3 py-2 text-sm text-zinc-200 outline-none focus:border-cyan-500" />
            <button onClick={handleSend} disabled={loading} className="px-4 py-2 bg-cyan-600 hover:bg-cyan-500 rounded text-sm font-medium disabled:opacity-50">Generate</button>
          </div>
        </div>
      </div>
    </div>
  );
};
